export function dotsFor(word: string, cx: number, cy: number, cell: number): [number, number][] {
  const w = word.toUpperCase();
  const totalW = w.length * 6 * cell - cell;
  const out: [number, number][] = [];
  w.split("").forEach((ch, k) => {
    const g = G[ch] ?? G["?"];
    for (let i = 0; i < 35; i++) {
      if (g[i] !== "1") continue;
      const col = i % 5;
      const row = Math.floor(i / 5);
      out.push([cx - totalW / 2 + (k * 6 + col) * cell + cell / 2, cy - 3.5 * cell + row * cell + cell / 2]);
    }
  });
  return out;
}

// Largest cell size that fits `word` into `maxW`.
export const dotCell = (word: string, maxW: number, max = 40) => Math.min(max, maxW / Math.max(1, word.length * 6 - 1));
