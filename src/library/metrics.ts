// Which table a CSS font stack uses (the first brand font it names).
function pick(font?: string): Table {
  if (!font) return FONTS.inter;
  const f = font.toLowerCase();
  const i = (s: string) => { const k = f.indexOf(s); return k < 0 ? 1e9 : k; };
  const order = [["inter", i("inter")], ["grotesk", i("grotesk")], ["serif", Math.min(i("instrument"), i("serif"))], ["mono", i("mono")]] as [string, number][];
  order.sort((a, b) => a[1] - b[1]);
  return order[0][1] < 1e9 ? FONTS[order[0][0]] : FONTS.inter;
}

function adv(ch: string, weight: number, tb: Table) {
  const i = ch === "ı" ? 73 : ch.charCodeAt(0) - 32; // dotless i measures like i
  const ws = Object.keys(tb).map(Number).sort((a, b) => a - b);
  const at = (w: number) => tb[w][i] ?? 600;
  if (ws.length === 1 || weight <= ws[0]) return at(ws[0]);
  if (weight >= ws[ws.length - 1]) return at(ws[ws.length - 1]);
  for (let k = 0; k < ws.length - 1; k++) {
    if (weight <= ws[k + 1]) return at(ws[k]) + ((at(ws[k + 1]) - at(ws[k])) * (weight - ws[k])) / (ws[k + 1] - ws[k]);
  }
  return at(ws[0]);
}

// Width in px of `s` at `size` px and `weight`, letter-spacing in em, in `font`.
export function textWidth(s: string, size: number, weight = 700, tracking = 0, font?: string) {
  const tb = pick(font);
  let sum = 0;
  for (const ch of s) sum += adv(ch, weight, tb) / 1000 + tracking;
  return sum * size;
}

// Left edge of each character, plus the total width as the last entry.
export function charX(s: string, size: number, weight = 700, tracking = 0, font?: string) {
  const tb = pick(font);
  const xs = [0];
  for (const ch of s) xs.push(xs[xs.length - 1] + (adv(ch, weight, tb) / 1000 + tracking) * size);
  return xs;
}
